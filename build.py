#!/usr/bin/env python3
"""Bundle src/ into one self-contained HTML document.

The document has to work from a file:// URL on a machine with no network and
no unpacking step - it is mailed around and opened from a download folder - so
the stylesheet, the script and every image are folded into a single file.

src/ is the same document with those parts kept as real files, which is what
you edit and what a static server hosts during development. Nothing about the
markup differs between the two: hydrateImages() in app.js assigns whatever
window.__TSRM_ASSETS__ holds for an id straight to img.src, and a relative URL
(development) serves there as well as a data: URI (bundle).

Usage:
  python3 build.py                    write dist/index.html
  python3 build.py -o FILE            write somewhere else
  python3 build.py --assets           regenerate src/assets/manifest.js only
  python3 build.py --check FILE       build, compare against FILE, write nothing
"""

import argparse
import base64
import json
import mimetypes
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "src"
ASSETS = SRC / "assets"
DEFAULT_OUT = ROOT / "dist" / "index.html"

STYLE_TAG = '<link rel="stylesheet" href="styles.css">'
ASSET_TAG = '<script id="tsrm-assets" src="assets/manifest.js"></script>'
SCRIPT_TAG = '<script src="app.js"></script>'

MANIFEST_HEADER = """\
/* Generated by build.py --assets. Development stand-in for the inlined
   base64 payload: hydrateImages() in app.js assigns these straight to
   img.src, and a relative URL serves as well as a data: URI. */
"""


def read(path):
    """Read text, keeping newlines exactly as they are on disk."""
    with open(path, encoding="utf-8", newline="") as fh:
        return fh.read()


def write(path, text):
    """Write text verbatim - no newline translation on any platform."""
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)


def asset_files():
    """Every image in src/assets, keyed by the data-asset id the markup uses.

    The id is the file name without its extension, so adding a room diagram is
    a matter of dropping the file in and rerunning --assets.
    """
    found = {}
    for path in sorted(ASSETS.iterdir()):
        if not path.is_file() or path.name == "manifest.js":
            continue
        mime, _ = mimetypes.guess_type(path.name)
        if mime is None or not mime.startswith("image/"):
            raise SystemExit("not a recognised image: %s" % path)
        key = path.stem
        if key in found:
            raise SystemExit("two files claim the asset id %r" % key)
        found[key] = (path, mime)
    return found


def manifest_text(files):
    """The development asset map that src/assets/manifest.js should hold."""
    body = {key: "assets/" + path.name for key, (path, _) in sorted(files.items())}
    return MANIFEST_HEADER + "window.__TSRM_ASSETS__ = " + json.dumps(body, indent=2) + ";\n"


def inline_assets(files):
    """The bundled asset map: every image as a data: URI, one copy each.

    A room diagram is shown on every session card held in that room, so the
    payload is stored once here and the markup carries only the id. Repeating
    the base64 at each use site would multiply the file several times over.

    Emitting it as JSON.parse of a string rather than as an object literal is
    the usual advice for a payload this size, and was tried here: interleaved
    over 12 runs each it came out 8 ms apart on a 4.3 MB payload, which is
    noise. The literal stays, because it is the simpler thing to emit and to
    read. What the load actually spends its time on is hydrating the images,
    which is handled in app.js.
    """
    body = {
        key: "data:%s;base64,%s" % (mime, base64.b64encode(path.read_bytes()).decode("ascii"))
        for key, (path, mime) in sorted(files.items())
    }
    # Separators without spaces: this line is already the bulk of the file.
    return "window.__TSRM_ASSETS__=" + json.dumps(body, separators=(",", ":")) + ";"


def substitute(html, tag, replacement):
    if html.count(tag) != 1:
        raise SystemExit(
            "src/index.html should contain %s exactly once, found %d"
            % (tag, html.count(tag))
        )
    return html.replace(tag, replacement)


def bundle():
    """The single-file document, as text."""
    files = asset_files()
    used = set()
    html = read(SRC / "index.html")
    for key in files:
        if ('data-asset="%s"' % key) in html:
            used.add(key)
    unused = sorted(set(files) - used)
    if unused:
        print("note: %d asset(s) not referenced by the markup: %s"
              % (len(unused), ", ".join(unused)), file=sys.stderr)

    html = substitute(html, STYLE_TAG, "<style>\n" + read(SRC / "styles.css") + "</style>")
    html = substitute(
        html, ASSET_TAG, '<script id="tsrm-assets">' + inline_assets(files) + "</script>"
    )
    html = substitute(html, SCRIPT_TAG, "<script>\n" + read(SRC / "app.js") + "</script>")
    return html


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("-o", "--out", type=pathlib.Path, default=DEFAULT_OUT,
                        help="where to write the bundle (default: dist/index.html)")
    parser.add_argument("--assets", action="store_true",
                        help="regenerate src/assets/manifest.js and stop")
    parser.add_argument("--check", type=pathlib.Path, metavar="FILE",
                        help="compare the bundle against FILE instead of writing it")
    args = parser.parse_args(argv)

    files = asset_files()
    if args.assets:
        write(ASSETS / "manifest.js", manifest_text(files))
        print("src/assets/manifest.js: %d asset(s)" % len(files))
        return 0

    # The manifest is generated, so a stale one is a bug waiting for the next
    # person who opens src/index.html directly. Say so rather than fix it
    # silently: the bundle does not read it, so the build itself is unaffected.
    if read(ASSETS / "manifest.js") != manifest_text(files):
        print("note: src/assets/manifest.js is out of date - run build.py --assets",
              file=sys.stderr)

    html = bundle()

    if args.check:
        reference = read(args.check)
        if html == reference:
            print("identical to %s (%d bytes)" % (args.check, len(html.encode("utf-8"))))
            return 0
        print("differs from %s: built %d bytes, reference %d bytes"
              % (args.check, len(html.encode("utf-8")), len(reference.encode("utf-8"))),
              file=sys.stderr)
        return 1

    args.out.parent.mkdir(parents=True, exist_ok=True)
    write(args.out, html)
    size = args.out.stat().st_size
    print("%s (%.1f MB, %d assets)" % (args.out, size / 1024 / 1024, len(files)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
